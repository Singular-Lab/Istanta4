    /// <summary>
    /// I20-1106 (Lotto 1): i tipi di backup di una promo. Sono due backup separati, come chiede
    /// la issue: i record dei tracciati e i record delle lavorazioni non si ripristinano insieme.
    /// </summary>
    public enum TipoBackupPromo : byte
    {
        TracciatiRecords = 1,
        LavorazioniRecords = 2
    }

    /// <summary>
    /// Una riga di promo_tracciati_records come sta nel backup: tutte le colonne, nessuna
    /// navigazione. Da una riga si riscrive un record esistente o se ne ricrea uno eliminato,
    /// con il suo Id originale, cosi' che cio' che lo riferiva lo ritrovi.
    /// </summary>
    public class RigaTracciatoBackup
    {
        public long Id { get; set; }
        public int IdTracciato { get; set; }
        public byte Versione { get; set; }
        public int IndiceLettura { get; set; }
        public int IndiceEsportazione { get; set; }
        public string? Label { get; set; }
        public string? Scatto { get; set; }
        public string? Codice { get; set; }
        public string? CodiceGruppo { get; set; }
        public string? Dato { get; set; }
        public bool? DaEsportare { get; set; }
        public int? IdAddestramento { get; set; }
        public DateTime? DataRegistrazione { get; set; }
        public byte ModalitaInserimento { get; set; }
        public byte Stato { get; set; }

        public static RigaTracciatoBackup Da(PromoTracciatiRecord r)
        {
            return new RigaTracciatoBackup
            {
                Id = r.Id,
                IdTracciato = r.IdTracciato,
                Versione = r.Versione,
                IndiceLettura = r.IndiceLettura,
                IndiceEsportazione = r.IndiceEsportazione,
                Label = r.Label,
                Scatto = r.Scatto,
                Codice = r.Codice,
                CodiceGruppo = r.CodiceGruppo,
                Dato = r.Dato,
                DaEsportare = r.DaEsportare,
                IdAddestramento = r.IdAddestramento,
                DataRegistrazione = r.DataRegistrazione,
                ModalitaInserimento = r.ModalitaInserimento,
                Stato = r.Stato
            };
        }

        /// <summary>Riscrive un record esistente con i valori salvati. L'Id non si tocca.</summary>
        public void ApplicaA(PromoTracciatiRecord r)
        {
            r.IdTracciato = IdTracciato;
            r.Versione = Versione;
            r.IndiceLettura = IndiceLettura;
            r.IndiceEsportazione = IndiceEsportazione;
            r.Label = Label;
            r.Scatto = Scatto;
            r.Codice = Codice;
            r.CodiceGruppo = CodiceGruppo;
            r.Dato = Dato;
            r.DaEsportare = DaEsportare;
            r.IdAddestramento = IdAddestramento;
            r.DataRegistrazione = DataRegistrazione;
            r.ModalitaInserimento = ModalitaInserimento;
            r.Stato = Stato;
        }

        /// <summary>Un record nuovo con l'Id originale: la colonna e' GENERATED BY DEFAULT e lo accetta.</summary>
        public PromoTracciatiRecord NuovaEntita()
        {
            var r = new PromoTracciatiRecord { Id = Id };
            ApplicaA(r);
            return r;
        }
    }

