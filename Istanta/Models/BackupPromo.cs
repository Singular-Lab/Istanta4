    /// <summary>Le promo della tendina di Backup promo, divise fra attive e non, ognuna dalla piu' recente.</summary>
    public class TendinaPromo
    {
        public List<Promo> attive { get; } = new List<Promo>();
        public List<Promo> altre { get; } = new List<Promo>();
    }

    /// <summary>
    /// I20-1106 (Lotto 1): backup e ripristino dei record di una promo, senza database. Il
    /// controller passa cio' che legge, e questa classe decide cosa diventa: il backup da salvare,
    /// l'elenco da mostrare, il piano del ripristino. E' anche il punto che la pulizia delle liste
    /// (Lotto 2) chiamera' prima di eliminare.
    /// </summary>
    public static class BackupPromo
    {
        /// <summary>
        /// Tutte le promo non eliminate, le attive davanti: un ripristino puo' servire anche a una
        /// promo chiusa, ma di solito serve a una in corso. Attiva vuol dire aperta e non ancora
        /// scaduta, la stessa regola della pagina Confronti. Dentro ogni gruppo, dalla piu' recente.
        /// </summary>
        public static TendinaPromo PromoPerLaTendina(IEnumerable<Promo> promo, DateTime adesso)
        {
            var tendina = new TendinaPromo();
            foreach (var p in promo.Where(p => p.Stato != (byte)StatoPromo.Eliminata).OrderByDescending(p => p.DataRegistrazione))
            {
                (PromoAttiva(p, adesso) ? tendina.attive : tendina.altre).Add(p);
            }
            return tendina;
        }

        /// <summary>Aperta e con una scadenza ancora da venire. Senza scadenza non e' attiva.</summary>
        public static bool PromoAttiva(Promo p, DateTime adesso)
        {
            return p.Stato == (byte)StatoPromo.Aperta && p.DataScadenza.HasValue && p.DataScadenza.Value > adesso;
        }

        public const string ORIGINE_OPERATORE = "Richiesta dell'operatore";
        public const string ORIGINE_PRE_RIPRISTINO = "Pre-ripristino";

        public const string MOTIVO_IMPAGINATO = "impaginato in una lavorazione";
        public const string MOTIVO_NEL_MENABO = "presente nel menabo'";
        public const string MOTIVO_TRACCIATO_ASSENTE = "il tracciato a cui apparteneva non esiste piu'";
        public const string MOTIVO_LAVORAZIONE_ASSENTE = "la lavorazione a cui apparteneva non esiste piu'";
        public const string MOTIVO_RECORD_ASSENTE = "il record del tracciato a cui era legata non esiste piu'";

        public const string TABELLA_TRACCIATI_RECORDS = "promo_tracciati_records";
        public const string TABELLA_LAVORAZIONI_RECORDS = "promo_lavorazioni_records";

        public static string DescriviTipo(byte tipo)
        {
            switch ((TipoBackupPromo)tipo)
            {
                case TipoBackupPromo.TracciatiRecords: return "Record dei tracciati";
                case TipoBackupPromo.LavorazioniRecords: return "Record delle lavorazioni";
                default: return "Tipo sconosciuto (" + tipo + ")";
            }
        }

        public static PromoBackup CreaTracciati(int idPromo, string origine, IEnumerable<PromoTracciatiRecord> righe, DateTime adesso)
        {
            var salvate = righe.Select(RigaTracciatoBackup.Da).ToList();
            return Crea(idPromo, TipoBackupPromo.TracciatiRecords, origine, salvate, adesso);
        }

        public static PromoBackup CreaLavorazioni(int idPromo, string origine, IEnumerable<PromoLavorazioniRecord> righe, DateTime adesso)
        {
            var salvate = righe.Select(RigaLavorazioneBackup.Da).ToList();
            return Crea(idPromo, TipoBackupPromo.LavorazioniRecords, origine, salvate, adesso);
        }

        private static PromoBackup Crea<TRiga>(int idPromo, TipoBackupPromo tipo, string origine, List<TRiga> salvate, DateTime adesso)
        {
            return new PromoBackup
            {
                IdPromo = idPromo,
                Tipo = (byte)tipo,
                DataBackup = adesso,
                Origine = origine,
                Conteggio = salvate.Count,
                Contenuto = JsonConvert.SerializeObject(salvate)
            };
        }

        public static List<RigaTracciatoBackup> LeggiTracciati(PromoBackup backup)
        {
            return Leggi<RigaTracciatoBackup>(backup, TipoBackupPromo.TracciatiRecords);
        }

        public static List<RigaLavorazioneBackup> LeggiLavorazioni(PromoBackup backup)
        {
            return Leggi<RigaLavorazioneBackup>(backup, TipoBackupPromo.LavorazioniRecords);
        }

        private static List<TRiga> Leggi<TRiga>(PromoBackup backup, TipoBackupPromo atteso)
        {
            if (backup.Tipo != (byte)atteso)
            {
                throw new InvalidOperationException("Il backup " + backup.Id + " e' di tipo \"" + DescriviTipo(backup.Tipo) + "\", non \"" + DescriviTipo((byte)atteso) + "\".");
            }
            return JsonConvert.DeserializeObject<List<TRiga>>(backup.Contenuto ?? "[]") ?? new List<TRiga>();
        }

        public static BackupPromoInfo Info(PromoBackup b)
        {
            return new BackupPromoInfo
            {
                id = b.Id,
                idPromo = b.IdPromo,
                tipo = b.Tipo,
                tipoDescrizione = DescriviTipo(b.Tipo),
                dataBackup = b.DataBackup,
                origine = b.Origine ?? string.Empty,
                conteggio = b.Conteggio
            };
        }

        /// <summary>L'elenco della pagina: dal piu' recente, senza contenuto.</summary>
        public static List<BackupPromoInfo> Elenco(IEnumerable<PromoBackup> backups)
        {
            return backups
                .OrderByDescending(b => b.DataBackup)
                .ThenByDescending(b => b.Id)
                .Select(Info)
                .ToList();
        }

        /// <param name="bloccati">Id dei record correnti che non si possono rimuovere, con il motivo (impaginati, nel menabo').</param>
        /// <param name="tracciatiEsistenti">Id dei tracciati della promo: una riga di un tracciato sparito non si puo' reinserire.</param>
        public static PianoRipristino<RigaTracciatoBackup> PianificaRipristinoTracciati(
            List<RigaTracciatoBackup> backup,
            IEnumerable<PromoTracciatiRecord> correnti,
            IDictionary<long, string> bloccati,
            ISet<int> tracciatiEsistenti)
        {
            return Pianifica(
                backup,
                correnti.Select(RigaTracciatoBackup.Da).ToList(),
                r => r.Id,
                r => r.Codice,
                r => tracciatiEsistenti.Contains(r.IdTracciato) ? null : MOTIVO_TRACCIATO_ASSENTE,
                id => bloccati.TryGetValue(id, out var motivo) ? motivo : null);
        }

        /// <param name="lavorazioniEsistenti">Id delle lavorazioni della promo.</param>
        /// <param name="recordEsistenti">Id dei record dei tracciati che esistono ancora, fra quelli che le righe del backup riferiscono.</param>
        public static PianoRipristino<RigaLavorazioneBackup> PianificaRipristinoLavorazioni(
            List<RigaLavorazioneBackup> backup,
            IEnumerable<PromoLavorazioniRecord> correnti,
            ISet<int> lavorazioniEsistenti,
            ISet<long> recordEsistenti)
        {
            return Pianifica(
                backup,
                correnti.Select(RigaLavorazioneBackup.Da).ToList(),
                r => r.Id,
                r => r.Codice,
                r => !lavorazioniEsistenti.Contains(r.IdLavorazione) ? MOTIVO_LAVORAZIONE_ASSENTE
                    : !recordEsistenti.Contains(r.IdRecordTracciato) ? MOTIVO_RECORD_ASSENTE
                    : null,
                id => null);
        }

        private static PianoRipristino<TRiga> Pianifica<TRiga>(
            List<TRiga> backup,
            List<TRiga> correnti,
            Func<TRiga, long> idDi,
            Func<TRiga, string?> codiceDi,
            Func<TRiga, string?> motivoNonInseribile,
            Func<long, string?> motivoNonRimovibile)
        {
            var piano = new PianoRipristino<TRiga>();
            var correntiPerId = correnti.ToDictionary(idDi);
            var visti = new HashSet<long>();

            foreach (var riga in backup)
            {
                long id = idDi(riga);
                // Un Id doppio nel backup non deve diventare due inserimenti: vale la prima riga.
                if (!visti.Add(id))
                {
                    continue;
                }

                if (correntiPerId.TryGetValue(id, out var corrente))
                {
                    if (Impronta(riga) == Impronta(corrente))
                    {
                        piano.invariati++;
                    }
                    else
                    {
                        piano.daAggiornare.Add(riga);
                    }
                    continue;
                }

                string? motivo = motivoNonInseribile(riga);
                if (motivo == null)
                {
                    piano.daInserire.Add(riga);
                }
                else
                {
                    piano.nonInseribili.Add(Segnalazione(id, codiceDi(riga), motivo));
                }
            }

            foreach (var corrente in correnti)
            {
                long id = idDi(corrente);
                if (visti.Contains(id))
                {
                    continue;
                }

                string? motivo = motivoNonRimovibile(id);
                if (motivo == null)
                {
                    piano.daRimuovere.Add(id);
                }
                else
                {
                    piano.nonRimovibili.Add(Segnalazione(id, codiceDi(corrente), motivo));
                }
            }

            return piano;
        }

        private static string Impronta<TRiga>(TRiga riga)
        {
            return JsonConvert.SerializeObject(riga);
        }

        private static SegnalazioneRipristino Segnalazione(long id, string? codice, string motivo)
        {
            return new SegnalazioneRipristino { id = id, codice = codice ?? string.Empty, motivo = motivo };
        }

        /// <summary>
        /// Dopo aver reinserito righe con il loro Id, la sequenza della colonna id va riportata
        /// oltre il massimo presente: non e' avanzata per quegli inserimenti, e un inserimento
        /// normale successivo non deve ricadere su un Id gia' preso.
        /// </summary>
        public static string SqlRiallineaSequenza(string tabella)
        {
            return "SELECT setval(pg_get_serial_sequence('" + tabella + "', 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM " + tabella + "), 1), true)";
        }
    }

    /// <summary>
    /// L'esito del ripristino per la pagina: i conteggi e le segnalazioni del piano, piu' il
    /// backup di sicurezza fatto prima di toccare i dati.
    /// </summary>
    public class RipristinoPromoRisposta
    {
        public bool esito { get; set; }
        public string error { get; set; } = string.Empty;
        public int aggiornati { get; set; }
        public int inseriti { get; set; }
        public int rimossi { get; set; }
        public int invariati { get; set; }
        public List<SegnalazioneRipristino> nonRimovibili { get; set; } = new List<SegnalazioneRipristino>();
        public List<SegnalazioneRipristino> nonInseribili { get; set; } = new List<SegnalazioneRipristino>();
        public int idBackupSicurezza { get; set; }

        public void Riporta<TRiga>(PianoRipristino<TRiga> piano)
        {
            aggiornati = piano.daAggiornare.Count;
            inseriti = piano.daInserire.Count;
            rimossi = piano.daRimuovere.Count;
            invariati = piano.invariati;
            nonRimovibili = piano.nonRimovibili.ToList();
            nonInseribili = piano.nonInseribili.ToList();
        }
    }
